// Windows "Open with" registration for the NSIS installer, from src-tauri/windows/open-with.json.
//
//   node scripts/open-with.mjs          rewrite the generated part of src-tauri/windows/installer-hooks.nsh
//   node scripts/open-with.mjs --check  exit 1 when it is out of date (tests/openWith.test.ts runs the same check)
//
// What it writes (HKCU only: the installer is installMode currentUser). Omniweave is offered in "Open with" for
// each type, and never made the default program: no `.ext` default value and no UserChoice are touched.
//   Software\Classes\Applications\omniweave.exe   FriendlyAppName, DefaultIcon, shell\open\command, SupportedTypes
//   Software\Classes\.<ext>\OpenWithProgids       value Omniweave.<Type>
//   Software\Classes\Omniweave.<Type>             type name (Korean installer: Korean, otherwise English), icon,
//                                                 shell\open\command
// The uninstaller removes exactly those (an OpenWithProgids or .<ext> key only when nothing else is left in it).
// .omw stays with Tauri's bundle.fileAssociations (Omniweave's own type, made the default).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const SPEC_PATH = root + "src-tauri/windows/open-with.json";
export const HOOKS_PATH = root + "src-tauri/windows/installer-hooks.nsh";
export const BEGIN = "; ---- BEGIN open-with (generated by scripts/open-with.mjs from open-with.json; do not edit) ----";
export const END = "; ---- END open-with ----";

export const readSpec = () => JSON.parse(readFileSync(SPEC_PATH, "utf8"));

const APP = "Software\\Classes\\Applications\\${MAINBINARYNAME}.exe";
const EXE = "$INSTDIR\\${MAINBINARYNAME}.exe";
const ICON = `$\\"${EXE}$\\",0`;
const OPEN = `$\\"${EXE}$\\" $\\"%1$\\"`;

/**
 * The registry entries, as data: [key, valueName, value] ("" = the key's default value). Keys are under HKCU.
 * The type name has both languages: { en, ko }.
 */
export function registryEntries(spec) {
  const out = [
    [APP, "FriendlyAppName", "${PRODUCTNAME}"],
    [APP + "\\DefaultIcon", "", ICON],
    [APP + "\\shell\\open\\command", "", OPEN],
  ];
  for (const t of spec.progIds) for (const e of t.exts) out.push([APP + "\\SupportedTypes", "." + e, ""]);
  for (const t of spec.progIds) {
    const k = "Software\\Classes\\" + t.id;
    out.push([k, "", { en: t.en, ko: t.ko }], [k + "\\DefaultIcon", "", ICON], [k + "\\shell\\open\\command", "", OPEN]);
    for (const e of t.exts) out.push([`Software\\Classes\\.${e}\\OpenWithProgids`, t.id, ""]);
  }
  return out;
}

const q = (s) => `"${s}"`;
// SHCNE_ASSOCCHANGED, SHCNF_IDLIST: Explorer re-reads the associations (the "Open with" list) at once
const NOTIFY = "  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'";

/** The NSIS macros OMW_OPEN_WITH_REGISTER / OMW_OPEN_WITH_UNREGISTER (CRLF lines, between BEGIN and END). */
export function nshSection(spec) {
  const L = [BEGIN, "!macro OMW_OPEN_WITH_REGISTER"];
  for (const [key, name, value] of registryEntries(spec)) {
    if (typeof value === "string") L.push(`  WriteRegStr HKCU ${q(key)} ${q(name)} ${q(value)}`);
    else {
      L.push("  ${If} $LANGUAGE == 1042", `    WriteRegStr HKCU ${q(key)} ${q(name)} ${q(value.ko)}`, "  ${Else}", `    WriteRegStr HKCU ${q(key)} ${q(name)} ${q(value.en)}`, "  ${EndIf}");
    }
  }
  L.push(NOTIFY, "!macroend", "", "!macro OMW_OPEN_WITH_UNREGISTER");
  L.push(`  DeleteRegKey HKCU ${q(APP)}`);
  for (const t of spec.progIds) {
    L.push(`  DeleteRegKey HKCU ${q("Software\\Classes\\" + t.id)}`);
    for (const e of t.exts) {
      const ext = `Software\\Classes\\.${e}`;
      L.push(`  DeleteRegValue HKCU ${q(ext + "\\OpenWithProgids")} ${q(t.id)}`);
      // only when empty: other programs' entries (values or subkeys) stay
      L.push(`  DeleteRegKey /ifempty /ifnovalues HKCU ${q(ext + "\\OpenWithProgids")}`, `  DeleteRegKey /ifempty /ifnovalues HKCU ${q(ext)}`);
    }
  }
  L.push(NOTIFY, "!macroend", END);
  return L.join("\r\n");
}

/** installer-hooks.nsh with its generated part replaced. */
export function withSection(hooks, spec) {
  const a = hooks.indexOf(BEGIN);
  const b = hooks.indexOf(END);
  if (a < 0 || b < a) throw new Error("installer-hooks.nsh: BEGIN/END open-with markers missing");
  // with a UTF-8 BOM: without one makensis reads an !include in the system code page and breaks the Korean names
  const bom = hooks.startsWith("﻿") ? "" : "﻿";
  return bom + hooks.slice(0, a) + nshSection(spec) + hooks.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const hooks = readFileSync(HOOKS_PATH, "utf8");
  const next = withSection(hooks, readSpec());
  if (process.argv.includes("--check")) {
    if (next !== hooks) {
      console.error("installer-hooks.nsh is out of date: run node scripts/open-with.mjs");
      process.exit(1);
    }
  } else if (next !== hooks) {
    writeFileSync(HOOKS_PATH, next);
    console.log("installer-hooks.nsh updated");
  }
}
